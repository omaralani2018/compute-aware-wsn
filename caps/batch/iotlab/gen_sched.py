"""PREREG16: transmit schedules for the replay, from the validation-selected reference on the test span (first N readings).
Writes app/sched.h and sched.json (with the energies predicted from the PREREG15 linear frame-cost model)."""
import sys, os, json, numpy as np
B=os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)),'..')); sys.path.insert(0,B)
import batch as bt; ol,fb=bt.ol,bt.fb
OUT=os.path.dirname(os.path.abspath(__file__))
N=1500; STREAMS=[('taxi',0),('traffic',0),('intel_time',0)]
def s2_events(col,D=25,cap=20):
    ev=[];buf=[]
    for t,r in enumerate(col):
        if r: buf.append(t)
        if buf and (len(buf)>=cap or t-buf[0]>=D-1): ev.append((t,5*len(buf))); buf=[]
    if buf: ev.append((len(col)-1,5*len(buf)))
    return ev
cells=[];meta={}
for ds,col in STREAMS:
    A,unit=ol.load(ds); A=np.asarray(A,float); A=A[:,None] if A.ndim==1 else A
    T=A.shape[0]; va=int(fb.SPLIT[1]*T); X=A[va-ol.LB:,col:col+1]
    name,f,_,_,_=ol.ref_arm(ds); F=bt.flags(X,f,unit)[:N,0]; n=len(F)
    s0=[(int(t),4) for t in np.flatnonzero(F)]
    s1=[(t,100) for t in range(24,n,25)]+([(n-1,4*(n%25))] if n%25 else [])
    s2=[(int(t),int(b)) for t,b in s2_events(F)]
    for sch,ev in (('S0',s0),('S1',s1),('S2',s2)): cells.append((f'{ds}_{sch}',ev,n))
    meta[ds]=dict(readings=n,column=col,reference=name,rho_prefix=float(1-F.mean()),reports=int(F.sum()))
pred={}
for nm,ev,n in cells:
    pred[nm]={nd:sum(bt.cost(nd,b) for _,b in ev)/n for nd in bt.PTS}
with open(os.path.join(OUT,'app','replay_tab.h'),'w') as h:
    h.write('/* generated by gen_sched.py (PREREG16); do not edit */\n#define N_CELLS %d\n'%len(cells))
    for i,(nm,ev,n) in enumerate(cells):
        h.write('static const uint16_t T%d[] = {%s};\nstatic const uint8_t L%d[] = {%s};\n'%(i,','.join(str(t) for t,_ in ev) or '0',i,','.join(str(b) for _,b in ev) or '0'))
    h.write('static const char *CN[] = {%s};\n'%','.join('"%s"'%c[0] for c in cells))
    h.write('static const uint16_t *CT[] = {%s};\nstatic const uint8_t *CL[] = {%s};\nstatic const uint16_t CNF[] = {%s};\n'%(
        ','.join('T%d'%i for i in range(len(cells))),','.join('L%d'%i for i in range(len(cells))),','.join(str(len(c[1])) for c in cells)))
    h.write('static const uint16_t CNR[] = {%s};\n'%','.join(str(c[2]) for c in cells))
json.dump(dict(N=N,streams=meta,cells={nm:dict(readings=n,frames=len(ev),bytes=sum(b for _,b in ev)) for nm,ev,n in cells},frame_sizes={nm:[b for _,b in ev] for nm,ev,n in cells},predicted_E_inc_per_reading_J=pred),
          open(os.path.join(OUT,'sched.json'),'w'),indent=1)
for nm,ev,n in cells: print('%-16s frames=%4d  pred M3 %.3e  nRF %.3e J/reading'%(nm,len(ev),pred[nm]['M3'],pred[nm]['nRF52840']))
print(meta)
